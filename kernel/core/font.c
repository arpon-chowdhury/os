void font_glyph(unsigned char byte, uint8_t rows[7]) {
    const uint8_t *glyph = 0;
    char ch = byte>=32 && byte<=126 ? (char)byte : '?';
    uint8_t extra[7] = {0};
    if (ch >= 'A' && ch <= 'Z') glyph = letters[ch - 'A'];
    else if (ch >= 'a' && ch <= 'z') glyph = lower[ch - 'a'];
    else if (ch >= '0' && ch <= '9') glyph = digits[ch - '0'];
    else if (ch >= ' ' && ch <= '?') glyph = punctuation[ch - ' '];
    else {
        switch (ch) {
        case '@': extra[0]=14;extra[1]=17;extra[2]=23;extra[3]=21;extra[4]=23;extra[5]=16;extra[6]=14;break;
        case '[': case ']': case '{': case '}':
            extra[0]=14;extra[6]=14;
            for (unsigned int i=1;i<6;++i) extra[i]=(ch=='[' || ch=='{')?8:2;
            if (ch=='{' || ch=='}') extra[3]=(ch=='{')?16:1;
            break;
        case '\\': extra[0]=16;extra[1]=8;extra[2]=8;extra[3]=4;extra[4]=2;extra[5]=2;extra[6]=1;break;
        case '^': extra[0]=4;extra[1]=10;extra[2]=17;break;
        case '_': extra[6]=31;break;
        case '`': extra[0]=8;extra[1]=4;break;
        case '|': for(unsigned int i=0;i<7;++i) extra[i]=4;break;
        case '~': extra[2]=9;extra[3]=22;break;
        default: break;
        }
        glyph = extra;
    }
    if (!glyph) glyph = punctuation[31];
    for (unsigned int r=0;r<7;++r) rows[r]=glyph[r];
}
